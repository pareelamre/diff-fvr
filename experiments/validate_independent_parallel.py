def rotation(angles):
    z,y,x=torch.deg2rad(angles);c,s=torch.cos,torch.sin
    zero=angles.new_zeros(());one=angles.new_ones(())
    stack=lambda rows:torch.stack([torch.stack(row) for row in rows])
    rz=stack([[c(z),-s(z),zero],[s(z),c(z),zero],[zero,zero,one]])
    ry=stack([[c(y),zero,s(y)],[zero,one,zero],[-s(y),zero,c(y)]])
    rx=stack([[one,zero,zero],[zero,c(x),-s(x)],[zero,s(x),c(x)]])
    return rz@ry@rx


def annotation_points(image,annotations):
    direction=annotations[0]['direction']
    native=nib.orientations.io_orientation(image.affine)
    transform=nib.orientations.ornt_transform(native,nib.orientations.axcodes2ornt(direction))
    annotation_affine=image.affine@nib.orientations.inv_ornt_aff(transform,image.shape)
    points=np.array([[a['X'],a['Y'],a['Z']] for a in annotations[1:]],dtype=float)
    if points.ndim!=2 or points.shape[1]!=3 or not len(points) or not np.isfinite(points).all():
        raise ValueError('Expected finite annotated voxel centroids')
    labels=[a['label'] for a in annotations[1:]]
    if len(set(labels))!=len(labels) or any(not isinstance(x,(int,float)) or x!=int(x) or not 1<=x<=28 for x in labels):
        raise ValueError('Invalid or duplicate vertebral labels')
    world=nib.affines.apply_affine(annotation_affine,points)
    native_points=nib.affines.apply_affine(np.linalg.inv(image.affine),world)
    if np.any(native_points< -1e-4) or np.any(native_points>np.array(image.shape)-1+1e-4):
        raise ValueError('Centroid outside CT voxel-center domain')
    return world


def spatial_projection(volume,spacing,pose,view,res,pitch,radius,ray_step=None):
    """Direct trilinear spatial quadrature, independent of Fourier sampling."""
    if view not in ('ap','lateral'):raise ValueError('Unknown parallel view')
    sz,sy,sx=spacing;D,H,W=volume.shape
    ray_step=min(spacing)/2 if ray_step is None else ray_step
    n=math.ceil(2*radius/ray_step)+1
    ray=torch.linspace(-radius,radius,n,device=volume.device)
    step=2*radius/(n-1)
    axis=(torch.arange(res,device=volume.device)-res//2)*pitch
    v,u=torch.meshgrid(axis,axis,indexing='ij')
    output=volume.new_zeros((res,res));rot=rotation(pose[:3])
    sizes=volume.new_tensor([W-1,H-1,D-1]);center=volume.new_tensor([W//2,H//2,D//2])
    scale=volume.new_tensor([sx,sy,sz])
    for start in range(0,n,32):
        r=ray[start:start+32,None,None].expand(-1,res,res)
        uu=u.expand_as(r);vv=v.expand_as(r)
        scanner=torch.stack([uu,vv,r] if view=='ap' else [r,vv,-uu],-1)
        obj=(scanner-pose[3:])@rot
        grid=2*(obj/scale+center)/sizes-1
        sampled=F.grid_sample(volume[None,None],grid[None],align_corners=True,padding_mode='zeros')[0,0]
        weights=volume.new_ones(len(r))
        if start==0:weights[0]=.5
        if start+len(r)==n:weights[-1]=.5
        output+=(sampled*weights[:,None,None]).sum(0)*step
    return output[None,None]


def relative_error(actual,expected):return float(((actual-expected).norm()/expected.norm().clamp_min(1e-12)).detach())


def require_qualification(records):
    limits={'torch.float32':(1e-4,3e-3),'torch.float16':(1e-2,2e-2),'torch.bfloat16':(1e-2,2e-2)}
    if len(records)!=3 or {r.get('dtype') for r in records}!=set(limits):
        raise ValueError('CUDA qualification requires all three declared precisions')
    for record in records:
        values=(record.get('image_relative_l2',float('nan')),record.get('gradient_relative_l2',float('nan')))
        if record.get('passed') is not True or any(not math.isfinite(v) or v>=limit for v,limit in zip(values,limits[record['dtype']])):
            raise ValueError('CUDA qualification failed declared forward/gradient bounds')


def cuda_qualification():
    """Actual optimized/fallback outputs and six-pose-parameter gradients."""
    from src.fvr.triton_slice import triton_slice_available
    axis=torch.arange(-12,13,device='cuda')
    z,y,x=torch.meshgrid(axis,axis,axis,indexing='ij')
    volume=torch.exp(-((x-3.)**2/12+(y+2.)**2/18+(z-1.)**2/9))
    results=[]
    for dtype in (torch.float32,torch.float16,torch.bfloat16):
        eager=TorchDiffFVREngine(volume,spacing=(1.1,.9,.7),device='cuda',dtype=dtype,detector_spacing=1.1,use_triton=False)
        optimized=TorchDiffFVREngine(volume,spacing=(1.1,.9,.7),device='cuda',dtype=dtype,detector_spacing=1.1,use_triton=True)
        if not triton_slice_available(optimized.f_vol_5d):raise ValueError('Actual Triton backend required for qualification')
        targets={v:eager(torch.tensor([[2.,-3.,1.,.2,-.1,.3]],device='cuda'),view=v,out_res=57).detach() for v in ('ap','lateral')}
        outputs=[];gradients=[]
        for engine in (eager,optimized):
            pose=torch.tensor([[-8.3,6.2,-4.7,-.6,.3,-.8]],device='cuda',requires_grad=True)
            images=[engine(pose,view=v,out_res=57) for v in targets]
            loss=sum((image-target).square().mean() for image,target in zip(images,targets.values()))
            outputs.append(torch.cat(images));gradients.append(torch.autograd.grad(loss,pose)[0])
        image_error=relative_error(outputs[1],outputs[0]);gradient_error=relative_error(gradients[1],gradients[0])
        tolerance=(1e-4,3e-3) if dtype==torch.float32 else (1e-2,2e-2)
        results.append(dict(dtype=str(dtype),image_relative_l2=image_error,gradient_relative_l2=gradient_error,
                            image_tolerance=tolerance[0],gradient_tolerance=tolerance[1],
                            passed=image_error<tolerance[0] and gradient_error<tolerance[1]))
    return results


def run(args):
    if not torch.cuda.is_available():raise ValueError('CUDA required for this qualification experiment')
    protocol=json.loads(args.protocol.read_text());selection=json.loads(args.selection.read_text())
    args.output.mkdir(parents=True,exist_ok=False)
    def save(report):
        temporary=args.output/'report.uploading';temporary.write_text(json.dumps(report,indent=2,allow_nan=False));temporary.replace(args.output/'report.json')
    report=dict(protocol=protocol,selection_sha256=hashlib.sha256(args.selection.read_bytes()).hexdigest(),
        protocol_sha256=hashlib.sha256(args.protocol.read_bytes()).hexdigest(),
        source_sha256={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in
            (Path(__file__),Path(__file__).with_name('verse_data.py'),Path(__file__).resolve().parents[1]/'src/fvr/torch_engine.py',Path(__file__).resolve().parents[1]/'src/fvr/triton_slice.py')},
        torch=torch.__version__,cuda=torch.version.cuda,gpu=torch.cuda.get_device_name(),
        cuda_qualification=cuda_qualification(),cases=[],status='qualifying',
        view_convention={'ap':'mathematical z-ray, u=+x v=+y; not anatomical AP','lateral':'mathematical x-ray, u=-z v=+y'},
        fidelity_criterion='Descriptive continuous errors; no predeclared population acceptance threshold.',
        optimization_timing_scope='Uncontrolled execution diagnostic including cold plans and host synchronization; not a comparative speed measurement.',
        limitations=['Independent anatomy but shared resampled CT attenuation and detector grid.',
                     'Noiseless synthetic parallel targets; no scatter, exposure, motion or calibration mismatch.',
                     'Only projection algorithm is independent; this does not estimate clinical or acquired-image generalization.'])
    save(report)
    try:require_qualification(report['cuda_qualification'])
    except ValueError:
        report['status']='qualification_failed';save(report);raise
    report['status']='running';save(report)
    inputs=download_cases(args.selection,args.data)
    for case_index,case in enumerate(inputs):
        raw=nib.load(args.data/case['ct_file'])
        points=annotation_points(raw,json.loads((args.data/case['centroids_file']).read_text()))
        image=nib.as_closest_canonical(raw)
        axes=image.affine[:3,:3];old_spacing=np.linalg.norm(axes,axis=0)
        if not np.allclose((axes/old_spacing).T@(axes/old_spacing),np.eye(3),atol=1e-4):raise ValueError('Sheared CT is unsupported')
        data=np.asarray(image.dataobj,dtype=np.float32)
        density=np.clip((data+1000.)/3000.,0,1)
        xyz_shape=np.maximum(8,np.rint(np.array(data.shape)*protocol['max_volume_axis']/max(data.shape))).astype(int)
        factors=(np.array(data.shape)-1)/(xyz_shape-1)
        xyz_spacing=old_spacing*factors
        volume=torch.from_numpy(density.transpose(2,1,0).copy())[None,None].cuda()
        volume=F.interpolate(volume,size=tuple(xyz_shape[::-1]),mode='trilinear',align_corners=True)[0,0]
        spacing=tuple(float(s) for s in xyz_spacing[::-1])
        local_points=(nib.affines.apply_affine(np.linalg.inv(image.affine),points)-xyz_shape//2*factors)*old_spacing
        fids=torch.tensor(local_points,device='cuda',dtype=torch.float32)
        radius=math.sqrt(sum(((n//2+.5)*s)**2 for n,s in zip(volume.shape,spacing)))
        pitch=2*(radius+protocol['detector_margin_mm'])/(protocol['detector_resolution']-1)
        truth=volume.new_tensor(protocol['target_pose'])
        with torch.no_grad():
            targets={v:spatial_projection(volume,spacing,truth,v,protocol['detector_resolution'],pitch,radius+protocol['detector_margin_mm']) for v in ('ap','lateral')}
        fidelity=[]
        primary=None
        for padding in protocol['padding_sensitivity']:
            engine=TorchDiffFVREngine(volume,spacing=spacing,pad_factor=padding,detector_spacing=pitch,use_triton=False)
            with torch.no_grad():
                for view,target in targets.items():
                    actual=engine(truth[None],view=view,out_res=protocol['detector_resolution'])
                    a=actual-actual.mean();b=target-target.mean()
                    error=relative_error(actual,target);ncc=float((a*b).sum()/(a.norm()*b.norm()))
                    if not math.isfinite(error) or not math.isfinite(ncc):raise ValueError('Nonfinite independent projection fidelity')
                    fidelity.append(dict(padding=padding,view=view,relative_l2=error,ncc=ncc))
            if padding==protocol['primary_padding']:primary=engine
        spectra={v:primary.prepare_spectral_target(target,high_pass=True) for v,target in targets.items()}
        gt_points=fids@rotation(truth[:3]).T+truth[3:]
        trials=[]
        for index in range(protocol['initializations_per_case']):
            rng=np.random.default_rng(protocol['seed']+100*case_index+index)
            delta=rng.uniform(-1,1,6)*np.array([protocol['initial_rotation_deg']]*3+[protocol['initial_translation_mm']]*3)
            initial=truth+volume.new_tensor(delta)
            angles=torch.nn.Parameter(initial[:3].clone());translation=torch.nn.Parameter(initial[3:].clone())
            optimizer=torch.optim.Adam([{'params':[angles],'lr':protocol['lr_rotation']},{'params':[translation],'lr':protocol['lr_translation']}])
            torch.cuda.synchronize();started=time.perf_counter();best=float('inf');best_pose=None
            for step in range(protocol['steps']):
                optimizer.zero_grad();pose=torch.cat([angles,translation])[None]
                loss=sum(primary.forward_spectral_ncc(pose,target,view=view,high_pass=True) for view,target in spectra.items())
                if not torch.isfinite(loss):raise RuntimeError('Nonfinite independent registration')
                if float(loss.detach())<best:best=float(loss.detach());best_pose=pose.detach()[0].clone()
                loss.backward();optimizer.step()
                factor=.1+.9*(1+math.cos(math.pi*(step+1)/protocol['steps']))/2
                for group,rate in zip(optimizer.param_groups,[protocol['lr_rotation'],protocol['lr_translation']]):group['lr']=rate*factor
            torch.cuda.synchronize();elapsed=time.perf_counter()-started
            initial_error=float((fids@rotation(initial[:3]).T+initial[3:]-gt_points).norm(dim=1).mean())
            error=float((fids@rotation(best_pose[:3]).T+best_pose[3:]-gt_points).norm(dim=1).mean())
            trials.append(dict(initialization=index,initial_pose=initial.tolist(),estimated_pose=best_pose.tolist(),initial_mtre_mm=initial_error,
                               final_mtre_mm=error,loss=best,optimization_s=elapsed,below_2mm=error<2.))
        case_result=dict(**case,resampled_shape_xyz=xyz_shape.tolist(),spacing_dhw_mm=spacing,landmarks=len(fids),fidelity=fidelity,trials=trials)
        report['cases'].append(case_result);save(report);print('INDEPENDENT_CASE_COMPLETE',case['subject'],flush=True)
        np.savez_compressed(args.output/(case['subject']+'_projections.npz'),**{view:target.cpu().numpy() for view,target in targets.items()})
        del primary,engine,volume,targets,spectra,optimizer;torch.cuda.empty_cache()
    report['status']='complete';save(report)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--protocol',type=Path,required=True);parser.add_argument('--selection',type=Path,required=True)
    parser.add_argument('--data',type=Path,required=True);parser.add_argument('--output',type=Path,required=True)
    run(parser.parse_args())


if __name__=='__main__':main()
